import thresholds from './income-thresholds.json' with { type: 'json' };

/**
 * Phase 2 field contract (§6). The questionnaire, the engine, and `validateProfile()`
 * all read this file, so a field that is not declared here cannot be answered,
 * cannot be referenced by a rule, and cannot be stored.
 *
 * Income bands are generated from the actual catalogue thresholds so that every
 * published threshold is a band edge. Run `npm run build:catalogue` to refresh
 * `catalogueThresholds` whenever a published income rule changes.
 */

export {
  PROFILE_FIELDS,
  ADDITIONAL_FIELDS,
  ANSWER_STATES,
  FORBIDDEN_FIELDS,
  isDeclaredField,
} from '../../../client/src/domain/profile/fields.js';

/**
 * Income thresholds (INR per year) referenced by published rules. Regenerated by
 * `npm run build:catalogue`; edit the scheme records, not this list.
 */
export const catalogueThresholds = thresholds;

/**
 * Build questionnaire income bands so that every catalogue threshold is a band edge.
 * The top band is open-ended (`max: null`).
 * @param {number[]} thresholds
 * @returns {{ id: string, label: string, value: import('../domain/types.js').IncomeInterval }[]}
 */
export function incomeBands(thresholds = catalogueThresholds) {
  const edges = [...new Set(thresholds.filter((n) => Number.isFinite(n) && n > 0))].sort(
    (a, b) => a - b,
  );
  const inr = (n) => `₹${n.toLocaleString('en-IN')}`;
  const bands = [];
  let previous = 0;
  for (const edge of edges) {
    bands.push({
      id: `upto-${edge}`,
      label: previous === 0 ? `Up to ${inr(edge)}` : `Above ${inr(previous)}, up to ${inr(edge)}`,
      value: {
        min: previous,
        max: edge,
        minInclusive: previous === 0,
        maxInclusive: true,
        currency: 'INR',
        period: 'year',
      },
    });
    previous = edge;
  }
  bands.push({
    id: `above-${previous}`,
    label: `Above ${inr(previous)}`,
    value: {
      min: previous,
      max: null,
      minInclusive: false,
      maxInclusive: false,
      currency: 'INR',
      period: 'year',
    },
  });
  return bands;
}

/**
 * Normalise a monthly figure to annual. Only called when the student explicitly
 * said the figure was monthly; never guessed.
 * @param {number} monthly
 * @returns {number}
 */
export function monthlyToAnnual(monthly) {
  if (!Number.isFinite(monthly) || monthly < 0) throw new RangeError('monthly must be >= 0');
  return monthly * 12;
}
